#!/usr/bin/env bash
# Generate package manager definitions for a published release.
#
# Usage: tools/gen-packages.sh <version> <dir-with-checksums.txt>
#
# Writes (relative to the repo root):
#   Formula/wperfk.rb    Homebrew:  brew tap sumeetchhetri/wperfk https://github.com/sumeetchhetri/wperfk
#   bucket/wperfk.json   Scoop:     scoop bucket add wperfk https://github.com/sumeetchhetri/wperfk
#   winget/*.yaml        winget:    manifests for microsoft/winget-pkgs (SumeetChhetri.wperfk)
set -euo pipefail

ver=${1:?usage: $0 <version> <dir>}
dir=${2:?usage: $0 <version> <dir>}
repo=${REPO:-sumeetchhetri/wperfk}
sums="$dir/wperfk_${ver}_checksums.txt"
base="https://github.com/$repo/releases/download/v$ver"
desc="HTTP benchmarking tool with Lua scripting: wrk and wrk2 modes in one binary"

sha() { # asset name -> sha256 from the checksums file
  local s
  s=$(awk -v f="$1" '$2 == f || $2 == "*"f {print $1}' "$sums")
  [ -n "$s" ] || { echo "missing $1 in $sums" >&2; exit 1; }
  echo "$s"
}

mac=wperfk_${ver}_darwin_universal.tar.gz
lx64=wperfk_${ver}_linux_amd64.tar.gz
larm=wperfk_${ver}_linux_arm64.tar.gz
wx64=wperfk_${ver}_windows_amd64.zip
warm=wperfk_${ver}_windows_arm64.zip

mkdir -p Formula bucket winget

cat > Formula/wperfk.rb <<EOF
# Generated by tools/gen-packages.sh for v$ver. Do not edit by hand.
class Wperfk < Formula
  desc "$desc"
  homepage "https://github.com/$repo"
  version "$ver"
  license "Apache-2.0"

  on_macos do
    url "$base/$mac"
    sha256 "$(sha "$mac")"
  end

  on_linux do
    on_intel do
      url "$base/$lx64"
      sha256 "$(sha "$lx64")"
    end
    on_arm do
      url "$base/$larm"
      sha256 "$(sha "$larm")"
    end
  end

  def install
    bin.install "wperfk"
    doc.install "README.md"
  end

  test do
    assert_match "wperfk #{version}", shell_output("#{bin}/wperfk -v")
  end
end
EOF

cat > bucket/wperfk.json <<EOF
{
    "version": "$ver",
    "description": "$desc",
    "homepage": "https://github.com/$repo",
    "license": "Apache-2.0",
    "architecture": {
        "64bit": {
            "url": "$base/$wx64",
            "hash": "$(sha "$wx64")"
        },
        "arm64": {
            "url": "$base/$warm",
            "hash": "$(sha "$warm")"
        }
    },
    "bin": "wperfk.exe",
    "checkver": {
        "github": "https://github.com/$repo"
    },
    "autoupdate": {
        "architecture": {
            "64bit": {
                "url": "https://github.com/$repo/releases/download/v\$version/wperfk_\$version_windows_amd64.zip"
            },
            "arm64": {
                "url": "https://github.com/$repo/releases/download/v\$version/wperfk_\$version_windows_arm64.zip"
            }
        },
        "hash": {
            "url": "\$baseurl/wperfk_\$version_checksums.txt"
        }
    }
}
EOF

id=SumeetChhetri.wperfk
schema=1.10.0
rm -f winget/*.yaml

cat > "winget/$id.yaml" <<EOF
# yaml-language-server: \$schema=https://aka.ms/winget-manifest.version.$schema.schema.json
PackageIdentifier: $id
PackageVersion: $ver
DefaultLocale: en-US
ManifestType: version
ManifestVersion: $schema
EOF

installer() { # arch url sha
  cat <<EOF
  - Architecture: $1
    InstallerUrl: $2
    InstallerSha256: $(echo "$3" | tr 'a-f' 'A-F')
EOF
}

cat > "winget/$id.installer.yaml" <<EOF
# yaml-language-server: \$schema=https://aka.ms/winget-manifest.installer.$schema.schema.json
PackageIdentifier: $id
PackageVersion: $ver
InstallerType: zip
NestedInstallerType: portable
NestedInstallerFiles:
  - RelativeFilePath: wperfk.exe
    PortableCommandAlias: wperfk
MinimumOSVersion: 10.0.0.0
Installers:
$(installer x64 "$base/$wx64" "$(sha "$wx64")")
$(installer arm64 "$base/$warm" "$(sha "$warm")")
ManifestType: installer
ManifestVersion: $schema
EOF

cat > "winget/$id.locale.en-US.yaml" <<EOF
# yaml-language-server: \$schema=https://aka.ms/winget-manifest.defaultLocale.$schema.schema.json
PackageIdentifier: $id
PackageVersion: $ver
PackageLocale: en-US
Publisher: Sumeet Chhetri
PublisherUrl: https://github.com/sumeetchhetri
PackageName: wperfk
PackageUrl: https://github.com/$repo
License: Apache-2.0
LicenseUrl: https://github.com/$repo/blob/main/LICENSE
ShortDescription: "$desc"
Tags:
  - benchmark
  - http
  - load-testing
  - lua
  - wrk
ReleaseNotesUrl: https://github.com/$repo/releases/tag/v$ver
ManifestType: defaultLocale
ManifestVersion: $schema
EOF

echo "Generated Formula/wperfk.rb, bucket/wperfk.json and winget/ for v$ver"
